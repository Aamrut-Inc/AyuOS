import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { METRIC_CATALOG } from "./metrics";

// Writes load/migrations/0013_agent_metric_catalog.sql from the code catalog.
// Migrations are plain SQL re-run on every start, so the catalog is turned
// into an idempotent upsert here. agent/catalog/catalog.test.ts fails when the
// file is out of date.

function lit(value: string | null): string {
  return value === null ? "NULL" : `'${value.replaceAll("'", "''")}'`;
}

export function seedSql(): string {
  const rows = METRIC_CATALOG.map((m) =>
    [
      lit(m.metric_type),
      lit(m.source_provider),
      lit(m.display_name),
      lit(m.definition),
      lit(m.unit_canonical),
      `ARRAY[${m.unit_aliases.map(lit).join(", ")}]::text[]`,
      lit(m.value_kind),
      m.ordinal_labels ? `${lit(JSON.stringify(m.ordinal_labels))}::jsonb` : "NULL",
      lit(m.comparable_group),
      lit(m.day_anchor),
      lit(m.stored_in),
      lit(m.cautions)
    ].join(", ")
  );
  return `-- GENERATED by agent/catalog/generate-seed.ts from agent/catalog/metrics.ts. Do not edit.
INSERT INTO agent.metric_catalog
  (metric_type, source_provider, display_name, definition, unit_canonical, unit_aliases,
   value_kind, ordinal_labels, comparable_group, day_anchor, stored_in, cautions)
VALUES
${rows.map((r) => `  (${r})`).join(",\n")}
ON CONFLICT (metric_type, source_provider) DO UPDATE SET
  display_name = EXCLUDED.display_name, definition = EXCLUDED.definition,
  unit_canonical = EXCLUDED.unit_canonical, unit_aliases = EXCLUDED.unit_aliases,
  value_kind = EXCLUDED.value_kind, ordinal_labels = EXCLUDED.ordinal_labels,
  comparable_group = EXCLUDED.comparable_group, day_anchor = EXCLUDED.day_anchor,
  stored_in = EXCLUDED.stored_in, cautions = EXCLUDED.cautions;
`;
}

export const SEED_PATH = join(import.meta.dir, "..", "..", "load", "migrations", "0013_agent_metric_catalog.sql");

if (import.meta.main) {
  writeFileSync(SEED_PATH, seedSql());
  console.log(`wrote ${METRIC_CATALOG.length} catalog rows to ${SEED_PATH}`);
}
